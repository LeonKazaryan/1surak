// Builds src/chat/map/landDots.ts: the world's land as a grid of dots, for the trip map.
// Natural Earth 110m land (public domain). Run: node scripts/build-land-dots.mjs (needs internet).
// Each row is a latitude with its runs of land: [lat, [lon, count, lon, count, …]], STEP degrees apart.
import { writeFileSync } from 'node:fs'

const SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
const STEP = 0.5
const NORTH = 83
const SOUTH = -56 // Antarctica left out, as in the globe of the loader

const land = await (await fetch(SOURCE)).json()
const polygons = land.features.flatMap((f) =>
  f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates,
)

function inRing(lon, lat, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}

const onLand = (lon, lat) =>
  polygons.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h)))

const rows = []
for (let lat = NORTH; lat >= SOUTH; lat -= STEP) {
  const runs = []
  let start = null
  for (let lon = -180; lon < 180; lon += STEP) {
    const hit = onLand(lon + STEP / 2, lat)
    if (hit && start === null) start = lon
    if (!hit && start !== null) {
      runs.push(start, Math.round((lon - start) / STEP))
      start = null
    }
  }
  if (start !== null) runs.push(start, Math.round((180 - start) / STEP))
  if (runs.length) rows.push([lat, runs])
}

const body = rows.map(([lat, runs]) => `[${lat},[${runs.join(',')}]]`).join(',')
writeFileSync(
  new URL('../src/chat/map/landDots.ts', import.meta.url),
  `// Generated by scripts/build-land-dots.mjs from Natural Earth 110m land (public domain). Do not edit.\n` +
    `// The world's land as dots ${STEP}° apart: each row is [lat, [lon, count, lon, count, …]].\n` +
    `export const DOT_STEP = ${STEP}\n` +
    `export const LAND_ROWS: [number, number[]][] = [${body}]\n`,
)
console.log(`${rows.length} rows, ${rows.reduce((n, [, r]) => n + r.length / 2, 0)} runs`)
